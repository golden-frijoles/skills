#!/usr/bin/env node
// vendor-ascii-pieces.mjs — copy ascii.rest's text pieces into the plugin as plain JavaScript (screensaver S1.5).
//
//   node scripts/vendor-ascii-pieces.mjs --from <a checkout of github.com/bas3line/ascii>
//
// The screensaver plays text in one ink, from these categories only — shapes, space, physics, nature, creatures,
// objects, generative, effects (the product owner, 2026-10-20: no logos, companies or distros, so no brand ever plays;
// no scenes: a colour picture squeezed into a terminal band lost too much). A piece qualifies when it has no `palette`
// (one ink: every terminal draws it crisply) and fits a band: at most MAX_COLS × MAX_ROWS cells. Each is copied with its
// TypeScript annotations stripped (Node's own stripTypeScriptTypes, so a Node 20 CI and any consumer's Node can import
// it) and nothing else changed; plugins/golden-frijoles/hooks/pieces/LICENSE keeps the MIT text, NOTICE credits them.
// A piece that imports anything, or touches the network, the process or eval, is refused: these run on the person's
// machine whenever the screensaver plays.
//
// Needs Node 22.13+ to run (stripTypeScriptTypes); what it writes runs on Node 18+. Zero deps.
import { readFileSync, readdirSync, writeFileSync, mkdirSync, copyFileSync, rmSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { isMain } from '../template/scripts/lib/is-main.mjs';

const OUT = join(dirname(fileURLToPath(import.meta.url)), '..', 'plugins', 'golden-frijoles', 'hooks', 'pieces');
export const CATEGORIES = ['shapes', 'space', 'physics', 'nature', 'creatures', 'objects', 'generative', 'effects'];
export const MAX_COLS = 100;
export const MAX_ROWS = 30;
// The side a crop keeps when a band is short (screensaver D3): a fire keeps its base, a tree its pot. Default: middle.
const ANCHORS = { bonsai: 'bottom', campfire: 'bottom', candle: 'bottom', fern: 'bottom', fountain: 'bottom', lighthouse: 'bottom', windmill: 'bottom' };

/** The piece's meta numbers and words, read from its source (no import needed to decide whether it qualifies). */
export function metaOf(src) {
  const word = (k) => new RegExp(`^\\s*${k}:\\s*"([^"]*)"`, 'm').exec(src)?.[1] ?? null;
  const num = (k) => Number(new RegExp(`^\\s*${k}:\\s*(\\d+)`, 'm').exec(src)?.[1] ?? NaN);
  return { name: word('name'), category: word('category'), cols: num('cols'), rows: num('rows'), palette: /^\s*palette:/m.test(src) };
}

/** Whether a piece plays: an allowed category, one ink, a band's size. */
export const qualifies = (m) =>
  CATEGORIES.includes(m.category) && !m.palette && m.cols > 0 && m.rows > 0 && m.cols <= MAX_COLS && m.rows <= MAX_ROWS;

/** Why a scene's source may not be vendored, or null. Pure: tested on fixtures. */
export function refusal(src) {
  const code = String(src).replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/.*$/gm, '');
  if (/^\s*import\s(?!type\b)/m.test(code)) return 'imports a module at run time';
  const bad = /\b(fetch|require|eval|Function|process|globalThis|XMLHttpRequest|WebSocket|Deno|Bun)\b\s*[.(]|\bimport\s*\(/.exec(code);
  return bad ? `uses ${bad[1] ?? 'import()'}` : null;
}

async function main(argv) {
  // Loaded here, not at the top: it exists from Node 22.13, and refusal() above is imported by a spec CI runs on Node 20.
  const { stripTypeScriptTypes } = await import('node:module');
  const at = argv.indexOf('--from');
  if (at === -1 || !argv[at + 1]) {
    process.stderr.write('usage: vendor-ascii-pieces.mjs --from <ascii checkout>\n');
    process.exit(2);
  }
  const from = argv[at + 1];
  const dir = join(from, 'src', 'pieces');
  rmSync(OUT, { recursive: true, force: true });
  mkdirSync(OUT, { recursive: true });
  const pieces = [];
  for (const file of readdirSync(dir).filter((f) => f.endsWith('.ts')).sort()) {
    const src = readFileSync(join(dir, file), 'utf8');
    const meta = metaOf(src);
    if (!qualifies(meta)) continue;
    const why = refusal(src);
    if (why) {
      process.stderr.write(`vendor-ascii-pieces: ${file} refused — it ${why}\n`);
      process.exit(1);
    }
    const id = file.replace(/\.ts$/, '');
    const js = stripTypeScriptTypes(src, { mode: 'strip' }).replace(/^\s*\n/gm, (m) => m);
    writeFileSync(join(OUT, `${id}.mjs`), `// ${id}.mjs — ascii.rest's "${id}" (github.com/bas3line/ascii, MIT — ./LICENSE), types stripped.\n${js}`);
    pieces.push({ id, name: meta.name ?? id, category: meta.category, cols: meta.cols, rows: meta.rows, ...(ANCHORS[id] ? { anchor: ANCHORS[id] } : {}) });
  }
  copyFileSync(join(from, 'LICENSE'), join(OUT, 'LICENSE'));
  writeFileSync(
    join(OUT, 'index.mjs'),
    `// GENERATED by scripts/vendor-ascii-pieces.mjs — the pieces the screensaver plays, in play order, with the size each\n// draws at (the band picks the ones that fit before anything is rendered).\nexport const PIECES = ${JSON.stringify(pieces, null, 2)};\n`
  );
  process.stdout.write(`vendor-ascii-pieces: wrote ${pieces.length} pieces to ${OUT}\n`);
}

if (isMain(import.meta.url)) await main(process.argv.slice(2));
