#!/usr/bin/env node
// vendor-ascii-scenes.mjs — copy ascii.rest's "scenes" into the plugin as plain JavaScript (screensaver S2).
//
//   node scripts/vendor-ascii-scenes.mjs --from <a checkout of github.com/bas3line/ascii>
//
// The screensaver plays only the `scenes` category: colour pictures, 200×100 square cells, a palette each. They are
// copied with their TypeScript annotations stripped (Node's own stripTypeScriptTypes, so a Node 20 CI and any
// consumer's Node can import them) and nothing else changed; plugins/golden-frijoles/hooks/scenes/LICENSE keeps the
// MIT text, NOTICE credits them. A scene that imports anything, or touches the network, the process or eval, is
// refused: these run on the person's machine whenever the screensaver plays.
//
// Needs Node 22.13+ to run (stripTypeScriptTypes); what it writes runs on Node 18+. Zero deps.
import { readFileSync, readdirSync, writeFileSync, mkdirSync, copyFileSync, rmSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { stripTypeScriptTypes } from 'node:module';
import { isMain } from '../template/scripts/lib/is-main.mjs';

const OUT = join(dirname(fileURLToPath(import.meta.url)), '..', 'plugins', 'golden-frijoles', 'hooks', 'scenes');

/** Why a scene's source may not be vendored, or null. Pure: tested on fixtures. */
export function refusal(src) {
  const code = String(src).replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/.*$/gm, '');
  if (/^\s*import\s(?!type\b)/m.test(code)) return 'imports a module at run time';
  const bad = /\b(fetch|require|eval|Function|process|globalThis|XMLHttpRequest|WebSocket|Deno|Bun)\b\s*[.(]|\bimport\s*\(/.exec(code);
  return bad ? `uses ${bad[1] ?? 'import()'}` : null;
}

function main(argv) {
  const at = argv.indexOf('--from');
  if (at === -1 || !argv[at + 1]) {
    process.stderr.write('usage: vendor-ascii-scenes.mjs --from <ascii checkout>\n');
    process.exit(2);
  }
  const from = argv[at + 1];
  const dir = join(from, 'src', 'pieces');
  rmSync(OUT, { recursive: true, force: true });
  mkdirSync(OUT, { recursive: true });
  const scenes = [];
  for (const file of readdirSync(dir).filter((f) => f.endsWith('.ts')).sort()) {
    const src = readFileSync(join(dir, file), 'utf8');
    if (!/category:\s*"scenes"/.test(src)) continue;
    const why = refusal(src);
    if (why) {
      process.stderr.write(`vendor-ascii-scenes: ${file} refused — it ${why}\n`);
      process.exit(1);
    }
    const id = file.replace(/\.ts$/, '');
    const js = stripTypeScriptTypes(src, { mode: 'strip' }).replace(/^\s*\n/gm, (m) => m);
    writeFileSync(join(OUT, `${id}.mjs`), `// ${id}.mjs — ascii.rest's "${id}" (github.com/bas3line/ascii, MIT — ./LICENSE), types stripped.\n${js}`);
    scenes.push(id);
  }
  copyFileSync(join(from, 'LICENSE'), join(OUT, 'LICENSE'));
  writeFileSync(
    join(OUT, 'index.mjs'),
    `// GENERATED by scripts/vendor-ascii-scenes.mjs — the scenes the screensaver plays, in play order.\nexport const SCENES = ${JSON.stringify(scenes, null, 2)};\n`
  );
  process.stdout.write(`vendor-ascii-scenes: wrote ${scenes.length} scenes to ${OUT}\n`);
}

if (isMain(import.meta.url)) main(process.argv.slice(2));
