#!/usr/bin/env node
// render-skill-adverts.mjs — the advertised skill list is GENERATED from plugins/golden-frijoles/skills/.
//
//   node scripts/render-skill-adverts.mjs            # rewrite every advert
//   node scripts/render-skill-adverts.mjs --check    # exit 1 if any advert is stale (CI)
//
// ── Why ───────────────────────────────────────────────────────────────────────────────────────
// The skill list used to be hand-maintained in FOUR places across three files — marketplace.json's own
// description, its plugin entry's description, plugin.json, and the README — in different orders, and
// by 2026-09-17 they disagreed (the marketplace's plugin entry had silently dropped prose-draft). A
// hand-kept advert is how a dark or deleted skill lingers in front of every consumer. Now the skills
// directory is the only list: each SKILL.md carries a one-line `summary:` in its frontmatter, and this
// renders every advert from it. Add or remove a skill directory, run this, and every advert follows;
// forget to run it and CI fails. (plugin-audit-and-extraction S1, story 1.6.)
//
// The prose AROUND each list is owned here too, so the whole description field is reproducible. The
// README is rewritten only between its `<!-- skills:start -->` / `<!-- skills:end -->` markers.
//
// Zero deps — Node 18+.

import { readFileSync, writeFileSync, readdirSync, existsSync, statSync, realpathSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { parseRequiresScripts } from './check-skill-scripts.mjs';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');
const SKILLS_DIR = join(ROOT, 'plugins', 'golden-frijoles', 'skills');
const MARKETPLACE = join(ROOT, '.claude-plugin', 'marketplace.json');
const PLUGIN = join(ROOT, 'plugins', 'golden-frijoles', '.claude-plugin', 'plugin.json');
const README = join(ROOT, 'README.md');

export const START = '<!-- skills:start — GENERATED by scripts/render-skill-adverts.mjs; edit each SKILL.md\'s `summary:` instead -->';
export const END = '<!-- skills:end -->';

/** Pure — read `name:` and `summary:` from a SKILL.md's frontmatter. Throws, naming the file, if either is absent. */
export function parseSkillHeader(source, file = 'SKILL.md') {
  source = source.replace(/\r\n/g, '\n'); // a CRLF checkout must parse the same as LF
  if (!source.startsWith('---\n')) throw new Error(`${file}: no frontmatter`);
  const close = source.indexOf('\n---\n', 3);
  if (close === -1) throw new Error(`${file}: frontmatter is never closed`);
  const fm = source.slice(4, close);
  const field = (key) => {
    const m = fm.match(new RegExp(`^${key}:\\s*(.+)$`, 'm'));
    if (!m) return null;
    const raw = m[1].trim();
    if (raw.length >= 2 && raw.startsWith('"') && raw.endsWith('"')) return JSON.parse(raw);
    // YAML single-quoted scalar: the only escape is '' for a literal quote.
    if (raw.length >= 2 && raw.startsWith("'") && raw.endsWith("'")) return raw.slice(1, -1).replace(/''/g, "'");
    return raw;
  };
  const name = field('name');
  const summary = field('summary');
  if (!name) throw new Error(`${file}: no name: in frontmatter`);
  if (!summary) throw new Error(`${file}: no summary: in frontmatter — every advertised skill needs a one-line summary`);
  return { name, summary };
}

/** Every skill directory with a SKILL.md, sorted — the one list every advert derives from. */
export function loadSkills(skillsDir = SKILLS_DIR) {
  return readdirSync(skillsDir)
    .filter((d) => statSync(join(skillsDir, d)).isDirectory() && existsSync(join(skillsDir, d, 'SKILL.md')))
    .sort()
    .map((d) => {
      const header = parseSkillHeader(readFileSync(join(skillsDir, d, 'SKILL.md'), 'utf8'), `${d}/SKILL.md`);
      if (header.name !== d) throw new Error(`${d}/SKILL.md: name "${header.name}" does not match its directory`);
      return header;
    });
}

/** Pure — the three JSON description fields. */
export function renderDescriptions(skills) {
  const names = skills.map((s) => s.name).join(', ');
  return {
    marketplace: `Golden Frijoles: the planning, build and operate skills (${skills.length}): ${names} — distributed from one versioned place.`,
    marketplacePlugin: `Golden Frijoles: the planning, build and operate skills (${skills.length}): ${names}.`,
    plugin: `Golden Frijoles: the planning, build and operate skills (${skills.length}): ${names}.`,
  };
}

export const KIT_START =
  "<!-- kit:start — GENERATED by scripts/render-skill-adverts.mjs from plugin.json's version; never edit by hand -->";
export const KIT_END = '<!-- kit:end -->';

/**
 * Pure — the run rule every script-wrapping SKILL.md carries (golden-frijoles-plugin D3), stamped with the kit
 * version the plugin release pins. Its text lives HERE only; each SKILL.md holds a generated copy.
 *
 * The rule is a literal shell line, not a paraphrase, so an agent runs exactly what CI tests
 * (render-skill-adverts.test.mjs executes it with a fake local script present and absent). npx needs no
 * --prefer-offline: with an exact pin, a warm cache serves a network outage (measured 2026-09-23, sprint-2.md).
 */
export function renderKitBlock(version) {
  return [
    KIT_START,
    "> **Running this skill's scripts.** Each `node scripts/<name>.mjs <args>` below means, from the project root:",
    `> \`if [ -f scripts/<name>.mjs ]; then node scripts/<name>.mjs <args>; else npx -y @golden-frijoles/kit@${version} <name> <args>; fi\``,
    "> The project's own copy always wins. The kit needs no install and copies nothing into the repo. If npx fails on",
    '> the network or the registry (ENOTFOUND, ECONNREFUSED, ETIMEDOUT, E404, a proxy error), report **could not',
    "> look: the kit is unreachable**, not a broken project, and offer to retry online or to copy the script into",
    "> `scripts/`. This covers the scripts the kit carries (`frijoles-kit --list`). Any other `scripts/` command here is",
    '> project tooling: if the project lacks it, say so and stop. Never re-implement a script\'s logic inline.',
    '> If a script prints `GF-NEEDS-SETTING {"key",…}`, ask the user that question once, save the answer with',
    `> \`npx -y @golden-frijoles/kit@${version} config set <key> <value>\` (always the kit, never local-wins: a project`,
    '> may own an unrelated `scripts/config.mjs`), tell them they can change it later the same way, and run the',
    '> script again if it exited 7.',
    KIT_END,
  ].join('\n');
}

/** Pure — replace the kit block in a SKILL.md. Throws when the markers are missing: placement is a human choice. */
export function spliceKitBlock(text, block, file = 'SKILL.md') {
  const a = text.indexOf('<!-- kit:start');
  const b = text.indexOf(KIT_END);
  if (a === -1 || b === -1 || b < a) {
    throw new Error(`${file}: wraps scripts but has no kit:start / kit:end markers — add them where the run rule belongs`);
  }
  return text.slice(0, a) + block + text.slice(b + KIT_END.length);
}

/** Pure — the README block between the markers. */
export function renderReadmeBlock(skills) {
  const rows = skills.map((s) => `| \`${s.name}\` | ${s.summary.replace(/\|/g, '\\|')} |`);
  return [START, '', '| Skill | What it does |', '|---|---|', ...rows, '', END].join('\n');
}

/** Pure — splice the block into README text. Throws if the markers are missing (a silent no-op would pass --check). */
export function spliceReadme(readme, block) {
  const a = readme.indexOf('<!-- skills:start');
  const b = readme.indexOf(END);
  if (a === -1 || b === -1 || b < a) throw new Error('README.md: the skills:start / skills:end markers are missing');
  return readme.slice(0, a) + block + readme.slice(b + END.length);
}

/** Compute every target file's rendered content. Pure given the inputs. */
export function renderAll({ skills, marketplaceText, pluginText, readmeText, skillTexts = {} }) {
  const d = renderDescriptions(skills);
  const marketplace = JSON.parse(marketplaceText);
  marketplace.description = d.marketplace;
  const entry = marketplace.plugins.find((p) => p.name === 'golden-frijoles');
  if (!entry) throw new Error('marketplace.json: no golden-frijoles plugin entry');
  entry.description = d.marketplacePlugin;
  const plugin = JSON.parse(pluginText);
  plugin.description = d.plugin;
  const kitBlock = renderKitBlock(plugin.version);
  const skillFiles = {};
  for (const [file, text] of Object.entries(skillTexts)) {
    // Only a skill that wraps scripts carries the run rule; a no-script skill has nothing to run.
    if ((parseRequiresScripts(text) ?? []).length) skillFiles[file] = spliceKitBlock(text, kitBlock, file);
  }
  return {
    [MARKETPLACE]: `${JSON.stringify(marketplace, null, 2)}\n`,
    [PLUGIN]: `${JSON.stringify(plugin, null, 2)}\n`,
    [README]: spliceReadme(readmeText, renderReadmeBlock(skills)),
    ...skillFiles,
  };
}

function main(argv) {
  const check = argv.includes('--check');
  const current = {
    [MARKETPLACE]: readFileSync(MARKETPLACE, 'utf8'),
    [PLUGIN]: readFileSync(PLUGIN, 'utf8'),
    [README]: readFileSync(README, 'utf8'),
  };
  const skillTexts = {};
  for (const s of loadSkills()) {
    const f = join(SKILLS_DIR, s.name, 'SKILL.md');
    skillTexts[f] = current[f] = readFileSync(f, 'utf8');
  }
  const next = renderAll({
    skills: loadSkills(),
    marketplaceText: current[MARKETPLACE],
    pluginText: current[PLUGIN],
    readmeText: current[README],
    skillTexts,
  });
  const stale = Object.keys(next).filter((f) => next[f] !== current[f]);
  const rel = (f) => f.slice(ROOT.length + 1);
  if (check) {
    if (!stale.length) {
      console.log('render-skill-adverts: every advert matches plugins/golden-frijoles/skills/.');
      return 0;
    }
    console.error(
      `render-skill-adverts: stale advert(s): ${stale.map(rel).join(', ')}\n` +
        '  The skill list is generated. Run `node scripts/render-skill-adverts.mjs` and commit the result —\n' +
        '  never hand-edit a skill list in these files.'
    );
    return 1;
  }
  for (const f of stale) writeFileSync(f, next[f]);
  console.log(stale.length ? `render-skill-adverts: wrote ${stale.map(rel).join(', ')}` : 'render-skill-adverts: already current.');
  return 0;
}

// realpath, not resolve: on macOS a temp or symlinked path (/var → /private/var) never equals the module
// URL, and a plain comparison makes the CLI a silent no-op.
const isMain = (() => {
  try {
    return !!process.argv[1] && realpathSync(process.argv[1]) === fileURLToPath(import.meta.url);
  } catch {
    return false;
  }
})();
if (isMain) process.exitCode = main(process.argv.slice(2));
